package model;

public class StorageZone3 {
    private int id;
    private String name;
    private SparePart3[] spareParts;

    public StorageZone3() {}

    public int getId() { return id; }
    public void setId(int id) { this.id = id; }
    public String getName() { return name; }
    public void setName(String name) { this.name = name; }
    public SparePart3[] getSpareParts() { return spareParts; }
    public void setSpareParts(SparePart3[] spareParts) { this.spareParts = spareParts; }
}
